#!/usr/bin/env node
/**
 * Post-processing of the static web export (dist/):
 *  1. generates dist/sw.js: a service worker that pre-caches every file of this version, so the app works
 *     offline once loaded. Cache name = hash of the files: a new deployment replaces the old cache.
 *  2. injects a strict Content-Security-Policy in dist/index.html. `connect-src 'none'` makes the browser
 *     refuse any fetch / XHR / WebSocket issued by the page: Moni cannot talk to any server.
 *
 * Usage: node scripts/build-pwa.mjs [dist]
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const dist = process.argv[2] ?? 'dist';

function walk(dir) {
  return readdirSync(dir).flatMap(name => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const EXCLUDED = new Set(['sw.js', 'metadata.json']);
const files = walk(dist)
  .map(p => '/' + relative(dist, p).split(sep).join('/'))
  .filter(p => !EXCLUDED.has(p.slice(1)) && !p.endsWith('.map'))
  .sort();

const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(dist, f)));
const version = hash.digest('hex').slice(0, 16);

const precache = files.map(f => (f === '/index.html' ? '/' : f));

const sw = `/* Moni service worker — generated by scripts/build-pwa.mjs. Same-origin app files only. */
const CACHE = 'moni-${version}';
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', event => {
  event.waitUntil(
    caches
      .keys()
      .then(keys => Promise.all(keys.filter(k => k.startsWith('moni-') && k !== CACHE).map(k => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  // Only the app's own files are handled; nothing else is ever requested by Moni.
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith(caches.match('/').then(cached => cached || fetch(request)));
    return;
  }
  event.respondWith(caches.match(request).then(cached => cached || fetch(request)));
});
`;
writeFileSync(join(dist, 'sw.js'), sw);

const csp = [
  "default-src 'self'",
  "script-src 'self'",
  // react-native-web injects its styles in <style> elements.
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self' data:",
  "connect-src 'none'",
  "worker-src 'self'",
  "manifest-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'none'",
].join('; ');

const indexPath = join(dist, 'index.html');
const html = readFileSync(indexPath, 'utf8');
if (!html.includes('<!-- CSP_PLACEHOLDER -->'))
  throw new Error('CSP placeholder missing in index.html');
writeFileSync(
  indexPath,
  html.replace(
    '<!-- CSP_PLACEHOLDER -->',
    `<meta http-equiv="Content-Security-Policy" content="${csp}" />`,
  ),
);

console.log(`PWA: ${precache.length} files pre-cached (cache moni-${version}), CSP injected.`);
